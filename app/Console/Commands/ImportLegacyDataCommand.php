<?php

namespace App\Console\Commands;

use App\Models\Client;
use App\Models\PortfolioCategory;
use App\Models\Project;
use App\Models\ProjectEnquiry;
use App\Models\ProjectMedia;
use App\Models\Media;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;
use PDO;

class ImportLegacyDataCommand extends Command
{
    /**
     * The name and signature of the console command.
     */
    protected $signature = 'import:legacy-data
                            {--source= : Path to the legacy SQLite database file}
                            {--dry-run : Simulate the migration and verify media assets without modifying the database}
                            {--clean-demo : Remove initial demo seed projects (cafe-08, villa-terra, residence-14-draft) after import}
                            {--include-tests : Also import historical automated test records (e.g. Secret Unpublished Villa)}
                            {--force : Force execution without interactive confirmation}';

    /**
     * The console command description.
     */
    protected $description = 'Safely import real architectural portfolio, verified media assets, categories, clients, and enquiries from legacy database';

    /**
     * Demo project slugs that can be safely retired when real portfolio data is active.
     */
    protected const DEMO_PROJECT_SLUGS = [
        'cafe-08',
        'villa-terra',
        'residence-14-draft',
    ];

    /**
     * Test artifacts generated by historical automated test suites.
     */
    protected const TEST_PROJECT_TITLES = [
        'Secret Unpublished Villa',
        'Public Project with Mixed Media',
        'Shah Sky Penthouse',
        'Vikram Mehta — Residential Villa',
        'Test Task Villa',
    ];

    /**
     * Execute the console command.
     */
    public function handle(): int
    {
        $sourcePath = $this->option('source');

        if (!$sourcePath) {
            $candidates = [
                base_path('../Studio-Desire-Original/backend/studio_desire.db'),
                base_path('database/studio_desire.db'),
                base_path('studio_desire.db'),
            ];

            foreach ($candidates as $candidate) {
                if (file_exists($candidate)) {
                    $sourcePath = $candidate;
                    break;
                }
            }

            if (!$sourcePath) {
                $this->error('No legacy database found. Please supply --source="path/to/studio_desire.db"');
                return self::FAILURE;
            }
        }

        if (!file_exists($sourcePath)) {
            $this->error("Legacy database file not found at: {$sourcePath}");
            return self::FAILURE;
        }

        $dryRun = (bool) $this->option('dry-run');
        $includeTests = (bool) $this->option('include-tests');

        $this->info("Connecting to legacy SQLite database: {$sourcePath}");
        if ($dryRun) {
            $this->warn('DRY RUN MODE ENABLED — Validating assets and records. No changes will be written.');
        }

        try {
            $legacyDb = new PDO("sqlite:{$sourcePath}", null, null, [
                PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
            ]);
        } catch (\Exception $e) {
            $this->error("Failed to connect to legacy database: {$e->getMessage()}");
            return self::FAILURE;
        }

        // Summary of source records
        $categoriesCount = $this->countTable($legacyDb, 'portfolio_categories');
        $clientsCount = $this->countTable($legacyDb, 'clients');
        $allProjectsCount = $this->countTable($legacyDb, 'projects');
        $projectMediaCount = $this->countTable($legacyDb, 'project_media');
        $enquiriesCount = $this->countTable($legacyDb, 'project_enquiries');

        // Audit projects in legacy DB
        $allLegacyProjects = $legacyDb->query("SELECT * FROM projects ORDER BY id ASC")->fetchAll();
        $realProjectsToImport = [];
        $skippedTestDuplicates = 0;
        $skippedDemoCount = 0;

        foreach ($allLegacyProjects as $p) {
            $title = trim($p['title'] ?? '');
            $isDemo = (bool) ($p['is_demo'] ?? false);

            if (in_array($title, self::TEST_PROJECT_TITLES, true)) {
                if (!$includeTests) {
                    $skippedTestDuplicates++;
                    continue;
                }
            }

            if ($isDemo && !in_array($p['slug'], ['hardikbhai'], true)) {
                $skippedDemoCount++;
                continue;
            }

            $realProjectsToImport[] = $p;
        }

        $this->table(
            ['Entity', 'Legacy Count', 'Selected for Import', 'Strategy & Validation'],
            [
                ['Categories', $categoriesCount, $categoriesCount, 'Match/Update by slug, preserve ordering & active status'],
                ['Clients', $clientsCount, $clientsCount, 'Deduplicate by email, preserve contact info & addresses'],
                ['Projects', $allProjectsCount, count($realProjectsToImport), "Genuine projects (skipped {$skippedTestDuplicates} test duplicates, {$skippedDemoCount} old demos)"],
                ['Total Media Rows', $projectMediaCount, 'Dynamic', 'Strict disk existence validation; link canonical Media IDs'],
                ['Enquiries', $enquiriesCount, $enquiriesCount, 'Preserve reference numbers, messages, and inquiry lifecycle'],
            ]
        );

        // Pre-validate media files on disk for projects to import
        $verifiedOnDisk = 0;
        $missingOnDisk = 0;
        $externalStockUrls = 0;
        $detailedMediaRows = [];

        foreach ($realProjectsToImport as $proj) {
            $projId = $proj['id'];
            $mediaRows = $legacyDb->query("SELECT * FROM project_media WHERE project_id = {$projId} ORDER BY sort_order ASC, id ASC")->fetchAll();

            // Check cover image
            if (!empty($proj['cover_image'])) {
                if (preg_match('/^https?:\/\//i', $proj['cover_image'])) {
                    $externalStockUrls++;
                } else {
                    $coverPath = public_path(ltrim($proj['cover_image'], '/\\'));
                    if (file_exists($coverPath)) {
                        $verifiedOnDisk++;
                    } else {
                        $missingOnDisk++;
                        $this->warn("Missing local cover image for [{$proj['title']}]: {$proj['cover_image']}");
                    }
                }
            }

            foreach ($mediaRows as $m) {
                $url = $m['url'] ?? '';
                if (preg_match('/^https?:\/\//i', $url)) {
                    $externalStockUrls++;
                    $detailedMediaRows[] = [
                        'Project' => $proj['title'],
                        'Media URL' => Str::limit($url, 35),
                        'Room' => $m['room_name'] ?? '—',
                        'Caption' => Str::limit($m['caption'] ?? '', 30),
                        'Status' => 'EXTERNAL (Stock/Unsplash)',
                    ];
                } else {
                    $relPath = ltrim($url, '/\\');
                    $diskPath = public_path($relPath);
                    $exists = !empty($relPath) && file_exists($diskPath);

                    if ($exists) {
                        $verifiedOnDisk++;
                    } else {
                        $missingOnDisk++;
                        $this->warn("Missing local project media for [{$proj['title']}]: {$url}");
                    }

                    $detailedMediaRows[] = [
                        'Project' => $proj['title'],
                        'Media URL' => $url,
                        'Room' => $m['room_name'] ?? '—',
                        'Caption' => Str::limit($m['caption'] ?? '', 30),
                        'Status' => $exists ? 'VERIFIED (Local Disk)' : 'MISSING ON DISK',
                    ];
                }
            }
        }

        $this->info("Media audit: {$verifiedOnDisk} local files verified on disk, {$missingOnDisk} missing, {$externalStockUrls} external URLs.");

        if ($dryRun) {
            $this->info('Dry run completed successfully. All records and physical files verified.');
            return self::SUCCESS;
        }

        if (!$this->option('force') && !$this->confirm('Proceed with live data import into current database?')) {
            $this->info('Import aborted by user.');
            return self::SUCCESS;
        }

        // Execute live import inside a transaction
        try {
            DB::transaction(function () use ($legacyDb, $realProjectsToImport) {
                // 1. Categories
                $this->info('Importing Portfolio Categories...');
                $categories = $legacyDb->query("SELECT * FROM portfolio_categories")->fetchAll();
                $categoryMap = [];
                foreach ($categories as $c) {
                    $cat = PortfolioCategory::updateOrCreate(
                        ['slug' => $c['slug'] ?? Str::slug($c['name'])],
                        [
                            'name' => $c['name'],
                            'description' => $c['description'] ?? null,
                            'display_order' => $c['display_order'] ?? 0,
                            'is_active' => (bool) ($c['is_active'] ?? true),
                        ]
                    );
                    $categoryMap[$c['id']] = $cat;
                }

                // 2. Clients
                $this->info('Importing Clients...');
                $clients = $legacyDb->query("SELECT * FROM clients")->fetchAll();
                $clientMap = [];
                foreach ($clients as $cl) {
                    $searchKey = !empty($cl['email']) ? ['email' => $cl['email']] : ['name' => $cl['name']];
                    $client = Client::updateOrCreate(
                        $searchKey,
                        [
                            'name' => $cl['name'],
                            'email' => $cl['email'] ?? null,
                            'phone' => $cl['phone'] ?? null,
                            'company' => $cl['company'] ?? null,
                            'address' => $cl['address'] ?? null,
                            'notes' => $cl['notes'] ?? null,
                            'status' => $cl['status'] ?? 'ACTIVE',
                        ]
                    );
                    $clientMap[$cl['id']] = $client;
                }

                // 3. Real Projects & Media
                $this->info('Importing Real Projects and verified media assets...');
                foreach ($realProjectsToImport as $p) {
                    $catId = $p['category_id'] ?? 1;
                    $targetCat = $categoryMap[$catId] ?? PortfolioCategory::first();
                    $clientId = $p['client_id'] ?? null;
                    $targetClient = $clientId ? ($clientMap[$clientId] ?? null) : null;

                    // Handle cover image media record
                    $coverMediaId = null;
                    $rawCover = $p['cover_image'] ?? null;
                    if (!empty($rawCover) && !preg_match('/^https?:\/\//i', $rawCover)) {
                        $coverRelPath = ltrim($rawCover, '/\\');
                        $coverDiskPath = public_path($coverRelPath);
                        if (file_exists($coverDiskPath)) {
                            $coverFilename = 'cover-' . Str::slug($p['title']) . '-' . basename($coverRelPath);
                            $coverMedia = Media::updateOrCreate(
                                ['url' => '/' . $coverRelPath],
                                [
                                    'filename' => $coverFilename,
                                    'original_name' => basename($coverRelPath),
                                    'mime_type' => 'image/webp',
                                    'file_size' => filesize($coverDiskPath),
                                    'media_type' => 'image',
                                    'title' => $p['title'] . ' Cover Image',
                                    'alt_text' => $p['title'] . ' Cover Image',
                                    'is_public' => true,
                                ]
                            );
                            $coverMediaId = $coverMedia->id;
                        }
                    }

                    $cleanCoverImage = $rawCover;
                    if (!empty($rawCover) && !preg_match('/^https?:\/\//i', $rawCover)) {
                        $cleanCoverImage = '/' . ltrim($rawCover, '/\\');
                    }

                    $project = Project::updateOrCreate(
                        ['slug' => $p['slug']],
                        [
                            'title' => $p['title'],
                            'subtitle' => $p['subtitle'] ?? null,
                            'category_id' => $targetCat?->id ?? 1,
                            'category' => $targetCat?->name ?? ($p['category'] ?? 'Residential'),
                            'client_id' => $targetClient?->id ?? null,
                            'location' => $p['location'] ?? null,
                            'year' => $p['year'] ?? null,
                            'project_type' => $p['project_type'] ?? null,
                            'area' => $p['area'] ?? null,
                            'description' => $p['description'] ?? null,
                            'cover_image' => $cleanCoverImage,
                            'cover_media_id' => $coverMediaId,
                            'publishing_status' => ($p['is_published'] ?? 1) ? 'published' : 'draft',
                            'is_published' => (bool) ($p['is_published'] ?? true),
                            'featured' => (bool) ($p['featured'] ?? false),
                            'vr_url' => $p['vr_url'] ?? null,
                        ]
                    );

                    // Import project media items
                    $legacyMedia = $legacyDb->query("SELECT * FROM project_media WHERE project_id = {$p['id']} ORDER BY sort_order ASC, id ASC")->fetchAll();
                    $this->info("Importing " . count($legacyMedia) . " media items for project [{$project->title}]...");

                    foreach ($legacyMedia as $m) {
                        $rawUrl = $m['url'] ?? '';
                        $isExternal = (bool) preg_match('/^https?:\/\//i', $rawUrl);
                        $mediaRecordId = null;
                        $storedUrl = $rawUrl;

                        if (!$isExternal && !empty($rawUrl)) {
                            $mRelPath = ltrim($rawUrl, '/\\');
                            $mDiskPath = public_path($mRelPath);
                            $storedUrl = '/' . $mRelPath;

                            // Create canonical Media record if exists on disk
                            if (file_exists($mDiskPath)) {
                                $uniqueFilename = Str::slug($p['title']) . '-' . basename($mRelPath);
                                $mediaRecord = Media::updateOrCreate(
                                    ['url' => $storedUrl],
                                    [
                                        'filename' => $uniqueFilename,
                                        'original_name' => basename($mRelPath),
                                        'mime_type' => 'image/webp',
                                        'file_size' => filesize($mDiskPath),
                                        'media_type' => 'image',
                                        'title' => $m['caption'] ?: pathinfo($mRelPath, PATHINFO_FILENAME),
                                        'alt_text' => $m['caption'] ?: $project->title,
                                        'is_public' => true,
                                    ]
                                );
                                $mediaRecordId = $mediaRecord->id;
                            }
                        }

                        // Create or update ProjectMedia record
                        ProjectMedia::updateOrCreate(
                            [
                                'project_id' => $project->id,
                                'url' => $storedUrl,
                            ],
                            [
                                'media_id' => $mediaRecordId,
                                'media_type' => $m['media_type'] ?? 'image',
                                'title' => $m['caption'] ?: pathinfo($rawUrl, PATHINFO_FILENAME),
                                'caption' => $m['caption'] ?? null,
                                'alt_text' => $m['caption'] ?? null,
                                'room_name' => $m['room_name'] ?? null,
                                'sort_order' => (int) ($m['sort_order'] ?? 0),
                                'is_published' => (bool) ($m['is_published'] ?? true),
                            ]
                        );
                    }
                }

                // 4. Enquiries
                $this->info('Importing Project Enquiries...');
                $enquiries = $legacyDb->query("SELECT * FROM project_enquiries")->fetchAll();
                foreach ($enquiries as $e) {
                    ProjectEnquiry::updateOrCreate(
                        ['reference_number' => $e['reference_number']],
                        [
                            'name' => $e['name'],
                            'email' => $e['email'],
                            'phone' => $e['phone'] ?? null,
                            'message' => $e['message'] ?? '',
                            'project_type' => $e['project_type'] ?? null,
                            'location' => $e['location'] ?? null,
                            'budget' => $e['budget'] ?? null,
                            'timeline' => $e['timeline'] ?? null,
                            'status' => strtoupper($e['status'] ?? 'NEW'),
                            'internal_notes' => $e['internal_notes'] ?? null,
                            'client_id' => $e['client_id'] ?? null,
                            'source' => $e['source'] ?? 'website',
                        ]
                    );
                }

                // 5. Clean up initial demo seeds if requested
                if ($this->option('clean-demo')) {
                    $this->info('Retiring disposable demo seed projects...');
                    $demoProjects = Project::whereIn('slug', self::DEMO_PROJECT_SLUGS)->get();
                    foreach ($demoProjects as $demoProj) {
                        $this->line("  - Removing demo seed project: {$demoProj->title} ({$demoProj->slug})");
                        $demoProj->media()->delete();
                        $demoProj->delete();
                    }
                }
            });

            $this->info('Legacy real portfolio data import completed successfully without data corruption or credential leakage.');
            return self::SUCCESS;
        } catch (\Exception $e) {
            $this->error("Data import failed and was rolled back cleanly: {$e->getMessage()}");
            return self::FAILURE;
        }
    }

    /**
     * Helper to safely count rows in a legacy SQLite table.
     */
    protected function countTable(PDO $db, string $table): int
    {
        try {
            return (int) $db->query("SELECT COUNT(*) FROM {$table}")->fetchColumn();
        } catch (\Exception) {
            return 0;
        }
    }
}
