-- 9. ROW-LEVEL SECURITY & DATA PROTECTION (CRITICAL SUPABASE SECURITY)
-- ------------------------------------------------------------------------------
-- By default, Supabase creates a RESTful Data API (PostgREST) on schema `public`.
-- We enable Row-Level Security (RLS) on all application tables and DO NOT grant
-- anonymous permissions, ensuring that private enquiries, users, and customer
-- data CANNOT be queried or scraped via the public Supabase URL.
--
-- Laravel connects directly via PostgreSQL connection pooler (as `postgres` user),
-- which bypasses RLS and retains complete, authorized access to all tables.

ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE password_reset_tokens ENABLE ROW LEVEL SECURITY;
ALTER TABLE sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE personal_access_tokens ENABLE ROW LEVEL SECURITY;
