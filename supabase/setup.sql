-- ==============================================================================
-- Application: Studio Desire Laravel Backend
-- Target: Supabase PostgreSQL (PostgreSQL 15+ / 16+)
-- License: Proprietary / Studio Desire
--
-- PURPOSE:
-- 1. Initializes the entire relational schema required by Studio Desire Laravel.
-- 2. Strictly adheres to Postgres best practices (indexed foreign keys, identity columns,
--    explicit constraints, proper timestamps).
-- 3. Protects data security: Enables Row-Level Security (RLS) and revokes public/anon
--    access to keep private customer data and owner records out of the Supabase Data API.
-- 4. Reconciles Laravel's `migrations` table so subsequent `php artisan migrate` calls
--    work seamlessly without errors or duplicate table conflicts.
--
-- SAFETY NOTICE:
-- - This script is NON-DESTRUCTIVE. It does NOT contain DROP TABLE, DROP SCHEMA, or TRUNCATE.
-- - Pre-execution checks verify whether application tables already exist. If an existing
--   schema is detected, the script terminates safely with a diagnostic notice.
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- 1. PRE-EXECUTION SAFETY CHECK
-- ------------------------------------------------------------------------------
DO $$
DECLARE
    existing_table_count INTEGER;
BEGIN
    SELECT COUNT(*)
    INTO existing_table_count
    FROM information_schema.tables
    WHERE table_schema = current_schema()
      AND table_name IN ('projects', 'media', 'project_enquiries', 'portfolio_categories', 'users');

    IF existing_table_count > 0 THEN
        RAISE EXCEPTION 'SAFETY CHECK FAILED: % core Studio Desire table(s) already exist in schema "%". Aborting script to avoid conflicts or duplicate definitions. If you wish to inspect existing tables, check the Supabase Table Editor.',
            existing_table_count, current_schema();
    END IF;

    RAISE NOTICE 'Pre-execution safety check passed: Target schema "%" is clean and ready for Studio Desire initialization.', current_schema();
END $$;

