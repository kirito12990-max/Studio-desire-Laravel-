-- 10. LARAVEL MIGRATION RECONCILIATION
-- ------------------------------------------------------------------------------
-- When initializing via this SQL script, we record all existing migrations in
-- Laravel's `migrations` table. This guarantees that subsequent executions of
-- `php artisan migrate` will detect that these migrations are already applied
-- and will NOT attempt to duplicate tables or error out.

CREATE TABLE IF NOT EXISTS migrations (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    migration VARCHAR(255) NOT NULL,
    batch INT NOT NULL
);

